def epoch_pairs(epochs):
    """Sorted consecutive (t0, t1) pairs of a timeline's epochs (dict or list)."""
    if isinstance(epochs, dict):
        ts = sorted(float(v) for v in epochs.values())
    else:
        ts = sorted(float(v) for v in epochs)
    return list(zip(ts, ts[1:]))


def max_gap_interval(epochs):
    """(gap_s, t0, t1) of the largest interval between consecutive events."""
    pairs = epoch_pairs(epochs)
    if not pairs:
        return None
    t0, t1 = max(pairs, key=lambda p: p[1] - p[0])
    return (t1 - t0, t0, t1)


def boundaries_crossed(a, b, windows):
    """Window-boundary epochs strictly inside the interval (a, b).

    Contiguous windows share boundary epochs (scale-out end == stable start);
    those are reported once as "x (= y)" instead of twice.
    """
    groups = {}
    for w in windows:
        short = WINDOW_SHORT.get(w["window"], w["window"])
        for kind, p in (("start", w["start_epoch"]), ("end", w["end_epoch"])):
            groups.setdefault(p, []).append(f"{short} {kind}")
    crossed = []
    for p, labels in sorted(groups.items()):
        if a < p < b:
            crossed.append(labels[0] + "".join(f" (= {other})" for other in labels[1:]))
    return crossed


def fmt_gap(v):
    return "-" if v is None else f"{v:.1f}"


def fmt_np(val, duration_s):
    """No-progress cell: an empty timeline's bound is the window duration."""
    if val is not None:
        return f"{val:.1f} s"
    return f"{duration_s} s (no in-window events)"


