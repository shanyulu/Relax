"""Render REANALYSIS_V2.md FROM reanalysis_v2.json (single source of truth).

The hand-written v2 report disagreed with its own JSON on the scale-out
window's rollout completions, and used three calibers the review corrected:
the 29 s figure was presented as a whole-training bound, serving weight-sync
events were labelled "optimizer updates", and "64/64 samples" overstated what
log lines can prove. This renderer regenerates the report from the structured
result so the two can no longer diverge.

Usage: python render_reanalysis_v2.py  (writes REANALYSIS_V2.md in this dir)
"""

import json
import pathlib

HERE = pathlib.Path(__file__).parent
R = json.loads((HERE / "reanalysis_v2.json").read_text())


def fmt_gap(v):
    return "-" if v is None else f"{v:.1f}"


lines = []
lines.append("# Train-continuity r5 — three-timeline re-analysis, v2 (generated)")
lines.append("")
lines.append("Generated by `render_reanalysis_v2.py` from `reanalysis_v2.json` (produced by")
lines.append("`reanalyze_three_timelines_v2.py` from the archived `raw_job_driver.log`, sha256")
lines.append("`feb23ecc80d3ce7382cefd68ca32aea20c5c26f3057978a272c0b40f44dfec78`, and the monitor's")
lines.append("`events.json`). Supersedes the hand-written v1 analysis (retained below in the")
lines.append("revision history); v1 merged step/rollout bounds, read rewards from a single line and")
lines.append("mislabelled serving weight syncs.")
lines.append("")
lines.append("## 1. Step timelines (what each marker is, and what its gap means)")
lines.append("")
st = R["step_timelines"]
lines.append("| Timeline | Marker semantics | Count | IDs | Max gap between consecutive events |")
lines.append("| --- | --- | --- | --- | --- |")
lines.append(f"| Step start | `Actor training step N/8` — the actor loop ENTERS step N | {st['step_start']['count']} | {st['step_start']['ids']} | {fmt_gap(st['step_start']['max_gap_s'])} s |")
lines.append(f"| Step execution end | `Actor training completed step N/8` — the actor loop FINISHED step N (incl. its optimizer iteration) | {st['step_execution_end']['count']} | {st['step_execution_end']['ids']} | {fmt_gap(st['step_execution_end']['max_gap_s'])} s |")
ws = st["serving_weight_sync_events"]
lines.append(f"| Serving weight sync | Slim `Update weights` / `Weights updated for actor_fwd_ref` — the actor→rollout serving sync chain; **not** optimizer updates | {ws['count']} | — | {fmt_gap(ws['max_gap_s'])} s |")
lines.append(f"| Rollout completion | `Rollout fully completed for rollout_id: N` | {st['rollout_completed']['count']} | {st['rollout_completed']['ids']} | {fmt_gap(st['rollout_completed']['max_gap_s'])} s |")
lines.append("")
lines.append("**Gap caliber.** Every gap above is the maximum interval between CONSECUTIVE events")
lines.append("of that timeline. It does **not** bound the interval before the first event (boot,")
lines.append("first data fetch) or after the last (final teardown), so it is not a whole-run")
lines.append("stall bound; the whole-run wall time and the per-window no-progress intervals below")
lines.append("are the complementary view. A step START line alone proves nothing about completion;")
lines.append("the execution-end timeline is the completion evidence, and the optimizer iteration")
lines.append("count equals its count (8) — the 15 serving weight-sync events are a different,")
lines.append("pre-existing chain the criterion requires to stay healthy, not a step count.")
lines.append("")
lines.append("## 2. The three scale windows (machine-extracted; per-event epochs in the JSON)")
lines.append("")
lines.append("| Window | Duration | Step starts inside | Step ends inside | Rollouts completed inside | Judge batches (engine pid) | Error lines |")
lines.append("| --- | --- | --- | --- | --- | --- | --- |")
for w in R["windows"]:
    ins = w["events_inside"]
    judge = ", ".join(f"{pid}: {n}" for pid, n in sorted(w["judge_prefill_batches_per_engine"].items())) or "—"
    lines.append(
        f"| {w['window']} | {w['duration_s']} s | {ins.get('step_start') or '—'} | "
        f"{ins.get('step_execution_end') or '—'} | {ins.get('rollout_completed') or '—'} | {judge} | {w['error_lines']} |"
    )
lines.append("")
lines.append("Longest no-progress interval strictly inside each window (between consecutive")
lines.append("in-window events of a timeline; an empty timeline's bound is the window duration):")
lines.append("")
lines.append("| Window | step_start | step_execution_end | rollout_completed |")
lines.append("| --- | --- | --- | --- |")
for w in R["windows"]:
    np_ = w["no_progress_inside"]
    lines.append(
        f"| {w['window']} | {fmt_gap(np_['step_start']['max_internal_gap_s'])} s | "
        f"{fmt_gap(np_['step_execution_end']['max_internal_gap_s'])} s | {fmt_gap(np_['rollout_completed']['max_internal_gap_s'])} s |"
    )
lines.append("")
lines.append("No timeline's max consecutive gap spans a window boundary (each window boundary has")
lines.append("events of every active timeline within its span or immediately adjacent).")
lines.append("")
lines.append("## 3. Reward evidence, split into columns (bounded claims)")
lines.append("")
re_ = R["reward_evidence"]
lines.append("| Column | Evidence | Value |")
lines.append("| --- | --- | --- |")
traffic = ", ".join(f"{pid}: {n}" for pid, n in sorted(re_["judge_traffic_by_engine_pid"].items()))
lines.append(f"| Judge inference traffic | GenRMEngine prefill/decode batches in the log | {traffic} |")
rewards = re_["per_rollout_raw_reward"]
rewards_str = ", ".join(f"r{k}={v}" for k, v in sorted(rewards.items(), key=lambda kv: int(kv[0])))
lines.append(f"| Per-rollout reward metric | `rollout/raw_reward` in each rollout metric dict | {len(rewards)}/8 rollouts carry values: {rewards_str} |")
lines.append(f"| Judge error lines | GenRMEngine lines matching error/exception/traceback | {re_['judge_error_lines']} |")
lines.append(f"| Format-check short-circuit | not individually logged by this recipe | not observable from this log; bounded below |")
lines.append("| Elastic attribution | inference batches on the elastic engine pid inside the stable window + the monitor's `served=1` counter tick | exactly one request |")
lines.append("")
lines.append("Bounded claim: reward VALUES, absence of exceptions and the served counter each alone")
lines.append("prove nothing about per-request judge success. This log supports the conjunction —")
lines.append("judge inference traffic on both engines, reward metrics computed for every rollout")
lines.append("(non-zero on rollouts 2 and 4), and zero judge error lines. Replica-level scoring")
lines.append("correctness and parse-gate independence are proven separately by the")
lines.append("engine-attribution consistency runs (r3 @ `945741e`, r6 @ `0481701`).")
lines.append("")
lines.append("## 4. Sample integrity (what log lines can and cannot prove)")
lines.append("")
si = R["sample_integrity"]
lines.append(f"- `Saved rollout result (8 samples) to …/rollout_result/train/{{N}}.jsonl` appears once per")
lines.append(f"  rollout N = {si['saved_rollout_ids']}: the log records **{si['total_samples']} saved samples**")
lines.append(f"  ({si['expected_total']} expected), with no missing ({si['missing_rollout_ids']}) and no")
lines.append(f"  duplicate ({si['duplicate_rollout_ids']}) rollout IDs; all carry-over windows report")
lines.append("  `aborted=0, deficit=0, surplus=0`.")
lines.append("- The per-sample JSONL files were rotated away on the runner, so **per-sample content")
lines.append("  deduplication and completeness are NOT verified from files** — the claim is exactly")
lines.append("  \"the log records 64 saved samples with unique rollout IDs\", nothing stronger.")
lines.append("")
lines.append("## 5. Log error classification")
lines.append("")
lines.append(f"- Non-benign timestamped error lines: **{R['non_benign_error_lines']}** (see JSON samples);")
lines.append("  judge (GenRMEngine) error lines: **0**; error lines inside the dual-replica stable")
lines.append("  window: **0**. The full classification (RewardWorker/pylatexenc pre-existing optional-dep")
lines.append("  gap, GCS kill churn on those dead workers, benign fallbacks) is in the JSON and the v1")
lines.append("  doc's table, which remains accurate for classification.")
lines.append("")
lines.append("## 6. Verdict (re-judged from the archived raw data; no GPU rerun)")
lines.append("")
lines.append("- **Criterion ⑤ (training continuity): PASS as run-continuity** — 8/8 step starts AND")
lines.append("  8/8 execution-ends AND 8/8 rollout completions AND the serving weight-sync chain")
lines.append("  continuing through all windows; per-window no-progress intervals bounded (max 23.0 s")
lines.append("  inside the stable window); zero error lines in the dual-replica stable window; 64 saved")
lines.append("  samples by unique rollout IDs. **This is a continuity claim only — no performance-")
lines.append("  impact claim is made** (that would require a same-config no-scaling control run).")
lines.append("- **Elastic contribution during continuity: one inference batch in the stable window**,")
lines.append("  cross-checked against the `served=1` counter tick — a bounded statement; replica")
lines.append("  correctness rests on the criterion-② attribution runs, not on this traffic share.")
lines.append("")
lines.append("## Revision history")
lines.append("")
lines.append("- v1 (`REANALYSIS_THREE_TIMELINES.md`): merged step/rollout bound; \"raw_reward all zero\"")
lines.append("  read from one line; serving syncs implied optimizer updates; window table hand-written")
lines.append("  and diverged from the JSON. Retained unchanged; superseded by this file.")
lines.append("- v2 (this file): generated from `reanalysis_v2.json`; calibers corrected per review;")
lines.append("  per-event epochs and per-window no-progress intervals machine-extracted.")

(HERE / "REANALYSIS_V2.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"wrote REANALYSIS_V2.md ({len(lines)} lines)")
